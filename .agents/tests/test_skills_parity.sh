#!/usr/bin/env bash
# Stage 2 of the skills layout (mirror strategy): .agents/skills is the canonical real directory,
# .claude/skills is generated from it by .agents/bin/sync-skills, and every skill is well formed.
# shellcheck source-path=SCRIPTDIR source=lib.sh
source "$(dirname "$0")/lib.sh"

SYNC="$REPO_ROOT/.agents/bin/sync-skills"

check_canonical() { # root: a real directory, not a link
  [ -d "$1/.agents/skills" ] && [ ! -L "$1/.agents/skills" ]
}
check_skills() { # root: name equals directory, description not empty
  local root="$1" bad=0 d name desc
  for d in "$root"/.agents/skills/*/; do
    d="${d%/}"
    [ -f "$d/SKILL.md" ] || { echo "no SKILL.md in ${d##*/}"; bad=1; continue; }
    name="$(yq --front-matter=extract '.name' "$d/SKILL.md")"
    desc="$(yq --front-matter=extract '.description' "$d/SKILL.md")"
    [ "$name" = "${d##*/}" ] || { echo "name [$name] differs from directory ${d##*/}"; bad=1; }
    { [ -n "$desc" ] && [ "$desc" != null ]; } || { echo "empty description in ${d##*/}"; bad=1; }
  done
  return $bad
}
check_no_plugin_refs() { ! grep -R "superpowers:" "$1/.agents/skills" "$1/.claude/skills"; }
check_drift() { "$SYNC" --check --root "$1"; }
tree_hash() { # dir: names, modes and contents
  (cd "$1" && find . -print0 | sort -z | xargs -0 stat -c '%n %a %F' && find . -type f -print0 | sort -z | xargs -0 sha256sum) | sha256sum
}

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

echo "-- real repository"
assert_ok ".agents/skills is a real directory (canonical)" check_canonical "$REPO_ROOT"
assert_ok ".claude/skills is not a symlink" test ! -L "$REPO_ROOT/.claude/skills"
assert_ok "every skill has name = directory and a description" check_skills "$REPO_ROOT"
assert_ok "no skill refers to a Superpowers skill" check_no_plugin_refs "$REPO_ROOT"
assert_ok "add-app and dev-workflow are present in both trees" test -f "$REPO_ROOT/.agents/skills/add-app/SKILL.md" -a -f "$REPO_ROOT/.agents/skills/dev-workflow/SKILL.md" -a -f "$REPO_ROOT/.claude/skills/add-app/SKILL.md" -a -f "$REPO_ROOT/.claude/skills/dev-workflow/SKILL.md"
assert_ok "generated mirror has no drift (test_skills_drift)" check_drift "$REPO_ROOT"

echo "-- sync-skills behaviour"
fixture "$TMP/s"; rm -rf "$TMP/s/.claude/skills"
assert_fails "check fails when the mirror is missing" check_drift "$TMP/s"
"$SYNC" --root "$TMP/s" >/dev/null
assert_ok "generate then check passes" check_drift "$TMP/s"
assert_ok "generated mirror equals the committed one" diff -r "$TMP/s/.claude/skills" "$REPO_ROOT/.claude/skills"
h1="$(tree_hash "$TMP/s/.claude/skills")"; "$SYNC" --root "$TMP/s" >/dev/null; h2="$(tree_hash "$TMP/s/.claude/skills")"
assert_ok "second run changes nothing (idempotent, deterministic)" test "$h1" = "$h2"
assert_ok "marker file names the generator" grep -q 'generated by .agents/bin/sync-skills' "$TMP/s/.claude/skills/GENERATED"
assert_fails "unknown option is a usage error" "$SYNC" --bogus

echo "-- negative fixtures"
fixture "$TMP/a"; rm -rf "$TMP/a/.agents/skills"; ln -s ../.claude/skills "$TMP/a/.agents/skills"
assert_fails "a link instead of the canonical directory is detected" check_canonical "$TMP/a"
fixture "$TMP/b"; sed -i 's/^name: add-app$/name: other/' "$TMP/b/.agents/skills/add-app/SKILL.md"
assert_fails "mismatched skill name is detected" check_skills "$TMP/b"
fixture "$TMP/c"; printf '\nSee superpowers:brainstorming.\n' >> "$TMP/c/.agents/skills/add-app/SKILL.md"
assert_fails "Superpowers reference is detected" check_no_plugin_refs "$TMP/c"
fixture "$TMP/d"; printf '\nhand edit\n' >> "$TMP/d/.claude/skills/add-app/SKILL.md"
assert_fails "hand edit in the mirror is drift" check_drift "$TMP/d"
fixture "$TMP/e"; printf '\nsource edit\n' >> "$TMP/e/.agents/skills/add-app/SKILL.md"
assert_fails "source edit without regenerating is drift" check_drift "$TMP/e"
fixture "$TMP/f"; mkdir "$TMP/f/.agents/skills/new-skill"
printf -- '---\nname: new-skill\ndescription: x\n---\n' > "$TMP/f/.agents/skills/new-skill/SKILL.md"
assert_fails "new skill missing from the mirror is drift" check_drift "$TMP/f"
fixture "$TMP/g"; printf 'x\n' > "$TMP/g/.claude/skills/stray.md"
assert_fails "extra file in the mirror is drift" check_drift "$TMP/g"
fixture "$TMP/h"; rm "$TMP/h/.claude/skills/GENERATED"
assert_fails "missing marker is drift" check_drift "$TMP/h"
fixture "$TMP/i"; chmod +x "$TMP/i/.claude/skills/add-app/SKILL.md"
assert_fails "mode change in the mirror is drift" check_drift "$TMP/i"
fixture "$TMP/j"; rm -rf "$TMP/j/.claude/skills"; ln -s ../.agents/skills "$TMP/j/.claude/skills"
assert_fails "a symlink as the mirror is rejected" check_drift "$TMP/j"
fixture "$TMP/k"; ln -s add-app "$TMP/k/.agents/skills/alias"
assert_fails "a symlink inside the source is rejected" "$SYNC" --root "$TMP/k"
finish

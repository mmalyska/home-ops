#!/usr/bin/env bash
# Writes the cluster's API versions, as ArgoCD passes them to `helm template --api-versions`:
# every group/version and every group/version/Kind. Charts such as bjw-s app-template check for
# the Kind form (gateway.networking.k8s.io/v1/HTTPRoute); without it they render an older API.
# Reads the cluster only. Usage: kube-api-versions.sh > kube-api-versions.txt
set -euo pipefail

server=$(kubectl version -o json | jq -r '.serverVersion.gitVersion' | sed -E 's/^v//; s/[-+].*$//')

echo "# kube-version: ${server}"
echo "# Generated by .taskfiles/lint/resources/kube-api-versions.sh (task lint:api-versions)."
echo "# Refresh after a Kubernetes upgrade or when an app adds or removes CRDs."
{
  kubectl api-versions
  # APIVERSION and KIND are the third-last and last columns; SHORTNAMES may be empty.
  kubectl api-resources --no-headers | awk '{ print $(NF-2) "/" $NF }'
} | LC_ALL=C sort -u
